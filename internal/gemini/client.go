const (
	DefaultDeveloperBaseURL = "https://generativelanguage.googleapis.com"
	DefaultTTSModel         = "gemini-3.1-flash-tts-preview"
	DefaultTTSVoice         = "Zephyr"
	DefaultSampleRate       = 24000
)

// StatusError represents an HTTP error from Gemini API.
type StatusError struct {
	StatusCode int
	Body       string
}

func (e *StatusError) Error() string {
	return fmt.Sprintf("gemini api error (%d): %s", e.StatusCode, e.Body)
}

// Client interacts with Vertex AI and Google AI Studio (Developer API) Gemini endpoints.
type Client struct {
	ProjectID        string
	Location         string
	APIKey           string
	HTTPClient       *http.Client
	TokenSource      oauth2.TokenSource
	VertexBaseURL    string // Optional override for testing
	DeveloperBaseURL string // Optional override for testing
	PCMToM4AConvert  func(pcmBytes []byte, sampleRate int) ([]byte, error)

	mu sync.Mutex
}

// NewClient creates a new Gemini Client.
func NewClient(projectID, location, apiKey string) *Client {
	if location == "" {
		location = "global"
	}
	return &Client{
		ProjectID:        projectID,
		Location:         location,
		APIKey:           apiKey,
		HTTPClient:       &http.Client{Timeout: 120 * time.Second},
		DeveloperBaseURL: DefaultDeveloperBaseURL,
		PCMToM4AConvert:  ConvertPCMToM4AWithFFmpeg,
	}
}

func (c *Client) getAccessToken(ctx context.Context) (string, error) {
	c.mu.Lock()
	ts := c.TokenSource
	c.mu.Unlock()

	if ts == nil {
		creds, err := google.FindDefaultCredentials(ctx, "https://www.googleapis.com/auth/cloud-platform")
		if err != nil {
			return "", fmt.Errorf("failed to find default credentials: %w", err)
		}
		c.mu.Lock()
		c.TokenSource = creds.TokenSource
		ts = c.TokenSource
		c.mu.Unlock()
	}

	tok, err := ts.Token()
	if err != nil {
		return "", fmt.Errorf("failed to obtain access token: %w", err)
	}
	return tok.AccessToken, nil
}

func (c *Client) vertexEndpoint(model, apiVersion string) string {
	if apiVersion == "" {
		apiVersion = "v1"
	}
	base := c.VertexBaseURL
	if base == "" {
		if c.Location == "global" {
			base = "https://aiplatform.googleapis.com"
		} else {
			base = fmt.Sprintf("https://%s-aiplatform.googleapis.com", c.Location)
		}
	}
	return fmt.Sprintf("%s/%s/projects/%s/locations/%s/publishers/google/models/%s:generateContent",
		strings.TrimRight(base, "/"), apiVersion, c.ProjectID, c.Location, model)
}

func (c *Client) developerEndpoint(model, apiVersion string) string {
	if apiVersion == "" {
		apiVersion = "v1beta"
	}
	base := c.DeveloperBaseURL
	if base == "" {
		base = DefaultDeveloperBaseURL
	}
	return fmt.Sprintf("%s/%s/models/%s:generateContent?key=%s",
		strings.TrimRight(base, "/"), apiVersion, model, c.APIKey)
}

// Content represents a single message turn in Gemini.
type Content struct {
	Role  string `json:"role,omitempty"`
	Parts []Part `json:"parts"`
}

// Part represents a single content part.
type Part struct {
	Text                string               `json:"text,omitempty"`
	Thought             bool                 `json:"thought,omitempty"`
	InlineData          *Blob                `json:"inlineData,omitempty"`
	FileData            *FileData            `json:"fileData,omitempty"`
	ExecutableCode      *ExecutableCode      `json:"executableCode,omitempty"`
	CodeExecutionResult *CodeExecutionResult `json:"codeExecutionResult,omitempty"`
}

// Blob represents inline binary data (base64 encoded in JSON).
type Blob struct {
	MimeType string `json:"mimeType"`
	Data     string `json:"data"`
}

// NewBytesPart creates a Part with base64-encoded inline bytes.
func NewBytesPart(data []byte, mimeType string) Part {
	return Part{
		InlineData: &Blob{
			MimeType: mimeType,
			Data:     base64.StdEncoding.EncodeToString(data),
		},
	}
}

// NewURIPart creates a Part referencing an external URI (e.g. YouTube video).
func NewURIPart(uri, mimeType string) Part {
	return Part{
		FileData: &FileData{
			MimeType: mimeType,
			FileURI:  uri,
		},
	}
}

// NewTextPart creates a text Part.
func NewTextPart(text string) Part {
	return Part{Text: text}
}

// FileData references a file by URI.
type FileData struct {
	MimeType string `json:"mimeType"`
	FileURI  string `json:"fileUri"`
}

// ExecutableCode represents code generated by Gemini code execution.
type ExecutableCode struct {
	Language string `json:"language,omitempty"`
	Code     string `json:"code,omitempty"`
}

// CodeExecutionResult represents output from Gemini code execution.
type CodeExecutionResult struct {
	Outcome string `json:"outcome,omitempty"`
	Output  string `json:"output,omitempty"`
}

// LatLng represents geographic coordinates.
type LatLng struct {
	Latitude  float64 `json:"latitude"`
	Longitude float64 `json:"longitude"`
}

// GroundingSource represents a cited web source from Google Search Grounding.
type GroundingSource struct {
	Title string `json:"title"`
	URI   string `json:"uri"`
}

// GenerateOptions configures a GenerateContent call.
type GenerateOptions struct {
	Model               string
	UseDeveloperAPI     bool
	APIVersion          string
	Contents            []Content
	SystemInstruction   *Content
	Temperature         *float32
	MaxOutputTokens     int
	ResponseMimeType    string
	ResponseSchema      map[string]any
	ThinkingBudget      *int
	EnableGoogleSearch  bool
	EnableGoogleMaps    bool
	EnableCodeExecution bool
	LatLng              *LatLng
	LanguageCode        string
	ResponseModalities  []string
	VoiceName           string
	Labels              map[string]string
}

type generateContentRequest struct {
	Contents          []Content         `json:"contents"`
	SystemInstruction *Content          `json:"systemInstruction,omitempty"`
	Tools             []map[string]any  `json:"tools,omitempty"`
	ToolConfig        map[string]any    `json:"toolConfig,omitempty"`
	GenerationConfig  map[string]any    `json:"generationConfig,omitempty"`
	Labels            map[string]string `json:"labels,omitempty"`
}

// GenerateContentResponse is the raw JSON structure returned by Gemini.
type GenerateContentResponse struct {
	Candidates []struct {
		Content           Content `json:"content"`
		FinishReason      string  `json:"finishReason,omitempty"`
		GroundingMetadata *struct {
			GroundingChunks []struct {
				Web *struct {
					URI   string `json:"uri"`
					Title string `json:"title"`
				} `json:"web,omitempty"`
			} `json:"groundingChunks,omitempty"`
		} `json:"groundingMetadata,omitempty"`
	} `json:"candidates"`
}

// GenerateResult holds parsed outputs from GenerateContent.
type GenerateResult struct {
	Text          string
	Sources       []GroundingSource
	Images        [][]byte
	AudioChunks   [][]byte
	AudioMimeType string
	RawResponse   *GenerateContentResponse
}

// GenerateContent invokes Gemini and parses text, grounding sources, images, and audio.
func (c *Client) GenerateContent(ctx context.Context, opts GenerateOptions) (*GenerateResult, error) {
	if opts.Model == "" {
		opts.Model = "gemini-3.1-flash-lite"
	}

	reqPayload := generateContentRequest{
		Contents:          opts.Contents,
		SystemInstruction: opts.SystemInstruction,
	}

	// Tools
	var tools []map[string]any
	if opts.EnableGoogleSearch {
		tools = append(tools, map[string]any{"googleSearch": map[string]any{}})
	}
	if opts.EnableGoogleMaps {
		tools = append(tools, map[string]any{
			"googleMaps": map[string]any{"enableWidget": false},
		})
	}
	if opts.EnableCodeExecution {
		tools = append(tools, map[string]any{"codeExecution": map[string]any{}})
	}
	if len(tools) > 0 {
		reqPayload.Tools = tools
	}

	// ToolConfig (for Maps Grounding latLng)
	if opts.LatLng != nil {
		lang := opts.LanguageCode
		if lang == "" {
			lang = "zh-TW"
		}
		reqPayload.ToolConfig = map[string]any{
			"retrievalConfig": map[string]any{
				"latLng": map[string]any{
					"latitude":  opts.LatLng.Latitude,
					"longitude": opts.LatLng.Longitude,
				},
				"languageCode": lang,
			},
		}
	}

	// GenerationConfig
	genCfg := make(map[string]any)
	if opts.Temperature != nil {
		genCfg["temperature"] = *opts.Temperature
	}
	if opts.MaxOutputTokens > 0 {
		genCfg["maxOutputTokens"] = opts.MaxOutputTokens
	}
	if opts.ResponseMimeType != "" {
		genCfg["responseMimeType"] = opts.ResponseMimeType
	}
	if opts.ResponseSchema != nil {
		genCfg["responseSchema"] = opts.ResponseSchema
	}
	if opts.ThinkingBudget != nil {
		genCfg["thinkingConfig"] = map[string]any{
			"thinkingBudget": *opts.ThinkingBudget,
		}
	}
	if len(opts.ResponseModalities) > 0 {
		genCfg["responseModalities"] = opts.ResponseModalities
	}
	if opts.VoiceName != "" {
		genCfg["speechConfig"] = map[string]any{
			"voiceConfig": map[string]any{
				"prebuiltVoiceConfig": map[string]any{
					"voiceName": opts.VoiceName,
				},
			},
		}
	}
	if len(genCfg) > 0 {
		reqPayload.GenerationConfig = genCfg
	}

	if !opts.UseDeveloperAPI {
		if len(opts.Labels) > 0 {
			reqPayload.Labels = opts.Labels
		} else {
			reqPayload.Labels = map[string]string{"client_id": "info_helper"}
		}
	}

	bodyBytes, err := json.Marshal(reqPayload)
	if err != nil {
		return nil, fmt.Errorf("failed to marshal gemini request: %w", err)
	}

	var endpoint string
	if opts.UseDeveloperAPI {
		endpoint = c.developerEndpoint(opts.Model, opts.APIVersion)
	} else {
		endpoint = c.vertexEndpoint(opts.Model, opts.APIVersion)
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(bodyBytes))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", "application/json")

	if !opts.UseDeveloperAPI {
		token, err := c.getAccessToken(ctx)
		if err != nil {
			return nil, err
		}
		req.Header.Set("Authorization", "Bearer "+token)
	}

	resp, err := c.HTTPClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()

	respBytes, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, err
	}

	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return nil, &StatusError{
			StatusCode: resp.StatusCode,
			Body:       string(respBytes),
		}
	}

	var raw GenerateContentResponse
	if err := json.Unmarshal(respBytes, &raw); err != nil {
		return nil, fmt.Errorf("failed to unmarshal gemini response: %w", err)
	}

	result := &GenerateResult{
		RawResponse: &raw,
	}

	if len(raw.Candidates) > 0 {
		cand := raw.Candidates[0]
		var textParts []string
		for _, part := range cand.Content.Parts {
			if part.Thought {
				continue
			}
			if part.Text != "" {
				textParts = append(textParts, part.Text)
			}
			if part.CodeExecutionResult != nil && part.CodeExecutionResult.Output != "" {
				textParts = append(textParts, fmt.Sprintf("[Code Output]: %s", part.CodeExecutionResult.Output))
			}
			if part.InlineData != nil && part.InlineData.Data != "" {
				decoded, err := base64.StdEncoding.DecodeString(part.InlineData.Data)
				if err == nil {
					if strings.HasPrefix(part.InlineData.MimeType, "image/") {
						result.Images = append(result.Images, decoded)
					} else if strings.HasPrefix(part.InlineData.MimeType, "audio/") {
						result.AudioChunks = append(result.AudioChunks, decoded)
						if result.AudioMimeType == "" {
							result.AudioMimeType = part.InlineData.MimeType
						}
					}
				}
			}
		}
		result.Text = strings.Join(textParts, "\n")

		if cand.GroundingMetadata != nil {
			for _, chunk := range cand.GroundingMetadata.GroundingChunks {
				if chunk.Web != nil && (chunk.Web.URI != "" || chunk.Web.Title != "") {
					title := chunk.Web.Title
					if title == "" {
						title = "Unknown"
					}
					result.Sources = append(result.Sources, GroundingSource{
						Title: title,
						URI:   chunk.Web.URI,
					})
				}
			}
		}
	}

	return result, nil
}

// ParseAudioMimeType extracts bits_per_sample and rate from an audio MIME type string
// e.g. "audio/L16;codec=pcm;rate=24000".
func ParseAudioMimeType(mimeType string) (bitsPerSample int, rate int) {
	bitsPerSample = 16
	rate = DefaultSampleRate

	parts := strings.Split(mimeType, ";")
	for _, param := range parts {
		param = strings.TrimSpace(param)
		lower := strings.ToLower(param)
		if strings.HasPrefix(lower, "rate=") {
			if r, err := strconv.Atoi(param[5:]); err == nil && r > 0 {
				rate = r
			}
		} else if strings.HasPrefix(param, "audio/L") {
			if b, err := strconv.Atoi(param[len("audio/L"):]); err == nil && b > 0 {
				bitsPerSample = b
			}
		}
	}
	return bitsPerSample, rate
}

// TextToSpeech synthesizes speech using Gemini 3.1 Flash TTS API and converts PCM to M4A.
func (c *Client) TextToSpeech(ctx context.Context, text string) ([]byte, int, error) {
	prompt := fmt.Sprintf("請使用台灣用語的繁體中文，以親切且自然的語氣朗讀以下摘要內容。## Transcript:\n%s", text)
	res, err := c.GenerateContent(ctx, GenerateOptions{
		Model:              DefaultTTSModel,
		UseDeveloperAPI:    true,
		APIVersion:         "v1beta",
		ResponseModalities: []string{"AUDIO"},
		VoiceName:          DefaultTTSVoice,
		Contents: []Content{
			{
				Role:  "user",
				Parts: []Part{NewTextPart(prompt)},
			},
		},
	})
	if err != nil {
		return nil, 0, err
	}

	var pcmBuf bytes.Buffer
	for _, chunk := range res.AudioChunks {
		pcmBuf.Write(chunk)
	}
	pcmBytes := pcmBuf.Bytes()
	if len(pcmBytes) == 0 {
		return nil, 0, fmt.Errorf("no audio received from Gemini TTS")
	}

	_, sampleRate := ParseAudioMimeType(res.AudioMimeType)
	if sampleRate <= 0 {
		sampleRate = DefaultSampleRate
	}

	// s16le = 2 bytes per sample
	durationMs := int(float64(len(pcmBytes)) / float64(sampleRate*2) * 1000)

	converter := c.PCMToM4AConvert
	if converter == nil {
		converter = ConvertPCMToM4AWithFFmpeg
	}
	m4aBytes, err := converter(pcmBytes, sampleRate)
	if err != nil {
		return nil, 0, err
	}

	return m4aBytes, durationMs, nil
}

// ConvertPCMToM4AWithFFmpeg converts s16le PCM bytes to M4A (AAC) using ffmpeg.
func ConvertPCMToM4AWithFFmpeg(pcmBytes []byte, sampleRate int) ([]byte, error) {
	pcmFile, err := os.CreateTemp("", "tts-*.pcm")
	if err != nil {
		return nil, err
	}
	pcmPath := pcmFile.Name()
	defer os.Remove(pcmPath)

	if _, err := pcmFile.Write(pcmBytes); err != nil {
		pcmFile.Close()
		return nil, err
	}
	pcmFile.Close()

	m4aPath := strings.TrimSuffix(pcmPath, ".pcm") + ".m4a"
	defer os.Remove(m4aPath)

	cmd := exec.Command(
		"ffmpeg", "-y",
		"-f", "s16le",
		"-ar", strconv.Itoa(sampleRate),
		"-ac", "1",
		"-i", pcmPath,
		"-c:a", "aac",
		m4aPath,
	)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("ffmpeg conversion failed: %w (%s)", err, stderr.String())
	}

	return os.ReadFile(m4aPath)
}
